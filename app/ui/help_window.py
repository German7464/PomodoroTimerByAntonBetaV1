HELP_TEXT = """Pomodoro Timer

Что такое Pomodoro
Pomodoro - это способ работать короткими сфокусированными периодами. Обычно пользователь работает 25 минут, затем делает короткий отдых. После нескольких рабочих периодов можно сделать длинный отдых.

Как пользоваться программой
Выберите настройки, нажмите "Старт" и работайте до конца периода. При автоматическом переходе программа сразу запустит следующий режим. При ручном переходе она продолжит прямой отсчет от нуля и будет ждать явного нажатия "Продолжить".

Кнопка "Старт"
Запускает отсчет текущего периода.

Кнопка "Пауза / Продолжить"
Останавливает отсчет без сброса времени. Повторное нажатие продолжает таймер с того же места.
Во время превышения эта кнопка недоступна: используйте отдельную кнопку продолжения следующего периода.

Кнопка "Пропустить период"
Сразу переводит таймер к следующему периоду. Такой период считается пропущенным и не засчитывается как завершенный.
Во время превышения пропуск заблокирован, чтобы накопленное время не потерялось.

Кнопка "Сброс"
Возвращает таймер к началу рабочего периода. В статистике это считается сбросом.
Во время превышения сброс заблокирован.

Кнопка "Продолжить и начать следующий период"
Появляется после завершения периода в ручном режиме. Она сохраняет накопленное превышение, переключает режим и сразу запускает следующий период. Кнопка доступна и тогда, когда уведомления отключены.

Режимы
Работа - время для сфокусированной работы.
Короткий отдых - короткая пауза после рабочего периода.
Длинный отдых - более длинная пауза после заданного количества рабочих периодов.
Переработка - время работы после завершения нормы.
Короткий отдых сверх нормы - продолжение короткого отдыха после нуля.
Длинный отдых сверх нормы - продолжение длинного отдыха после нуля.

Во всех трех состояниях превышение показывается со знаком "+" в выбранном формате, например +00:00:01 или +00:01.

Настройки
В настройках можно изменить длительности, отключить длинный отдых, выбрать формат времени HH:MM:SS или MM:SS, настроить тему, уведомления, виджет, профили, трей и автозапуск.
Двоичные настройки используют общий переключатель: ВЫКЛ означает ползунок слева, ВКЛ — справа. Состояние также различается текстом и цветом. Переключатель работает мышью, клавишей Пробел или Enter. Команды вроде "Старт", "Продолжить", "Предпросмотр" и "Применить" остаются обычными кнопками.

Оформление
На вкладке "Оформление" доступны темы Comet, Aurora, Warm и Пользовательская, каждая в светлом и тёмном режиме. Выбор применяется сразу ко всем открытым окнам и виджету, сохраняется для следующего запуска и не сбрасывает таймер.
Кнопка "Настроить цвета" открывает редактор двух пользовательских палитр. Их можно создать на основе встроенной темы, предварительно посмотреть, применить, отменить или сбросить к безопасной Comet. Некорректный формат #RRGGBB не принимается, а низкий контраст требует подтверждения.
Текстовая кнопка "Тёмный режим" или "Светлый режим" над таймером быстро меняет режим текущей темы. Кнопка и настройки используют один общий выбор.

Индикация превышения
На вкладке "Превышение" выбирается один основной эффект: без анимации, пульсация, увеличение цифр, сигнальные маячки, акцентная рамка или волна-индикатор. Изменение цвета включается отдельно и применяется к цифрам, карточке или обоим элементам. Скорость, интенсивность и движение настраиваются независимо.
Переработка, короткий и длинный отдых сверх нормы имеют независимые цвета. "По теме" использует цвет активной встроенной или пользовательской палитры. Кнопка "Предпросмотр" временно показывает выбранное состояние, но не запускает таймер, не меняет статистику и не показывает уведомление.
Главное окно и все виды виджета используют одну фазу. После "Продолжить", возврата к обычному периоду или выхода восстанавливаются цвет, размер цифр, рамка и индикаторы; знак "+" и текстовое название всегда сохраняются во время настоящего превышения. Переключатель "Делать виджет непрозрачным при превышении" временно устанавливает виджету 100%, а затем возвращает точное постоянное значение.

Уведомления
Если включен автоматический переход, уведомление будет информационным с кнопкой "Закрыть".
Если включен ручной переход, уведомление покажет кнопку "Продолжить", которая выполняет тот же безопасный переход, что и кнопка главного окна. Ручное уведомление не закрывается автоматически. Закрытие крестиком не продолжает таймер и не стирает превышение: продолжить всегда можно из главного окна.

Виджет
Доступны семь видов. Минималистичный показывает состояние и крупное время, компактный добавляет основную кнопку, а расширенный — цикл и команды управления. Микро обычно показывает только время, Строка размещает состояние, время и кнопку горизонтально, Кольцо показывает ход периода без значений выше 100%, Табло выделяет крупные моноширинные цифры.

Переключатель "Отображать виджет" на основном экране показывает ВКЛ для открытого виджета и ВЫКЛ для скрытого. Его изменение или крестик виджета используют один обработчик, не останавливают таймер и сохраняют выбор для следующего запуска. На вкладке настроек отдельного управления видимостью нет.

Для каждого типа в настройках можно выбрать маленький, средний или большой размер, непрозрачность от 5% до 100% и режим поверх окон. Чем ниже процент, тем прозрачнее виджет; значение применяется сразу и сохраняется с задержкой. Цвета берутся из общей темы; прежние отдельные поля цветов больше не редактируются. Окно можно изменять вручную стандартной рамкой Windows — тогда выбирается размер "Пользовательский". Размер и положение каждого типа сохраняются отдельно. Виджет можно перемещать мышью за свободную область, состояние или время.

Все виды показывают состояние одного общего таймера. При переработке или отдыхе сверх нормы отображаются правильное название, знак "+" и кнопка "Продолжить", использующая тот же безопасный переход, что главное окно.

Статистика
Статистика показывает обычное время работы и отдыха, завершенные периоды, пропуски, сбросы и полные Pomodoro-циклы за сегодня и за все время. Переработка, короткий отдых сверх нормы и длинный отдых сверх нормы показаны тремя отдельными строками и не входят в обычное время.

Безопасность ручного перехода
Пока считается превышение, старт, пауза, пропуск и сброс не меняют состояние. Закрытие главного окна в трей оставляет подсчет активным. При полном штатном выходе уже накопленное превышение сохраняется без запуска следующего периода.

Повторный запуск
Для текущего пользователя Windows работает только один экземпляр Pomodoro Timer. Повторный запуск покажет сообщение и завершится, не создавая второе окно. После обычного или аварийного завершения системная блокировка освобождается автоматически.

О программе
Pomodoro Timer - локальное настольное приложение на Python и Tkinter. Оно хранит настройки, профили и статистику на вашем компьютере."""


class HelpView(ttk.Frame):
    """Вкладка справки с прокручиваемым текстом."""

    def __init__(self, parent: tk.Widget) -> None:
        """Создает читаемую справку внутри вкладки."""
        super().__init__(parent, padding=16)
        self._build_ui()

    def _build_ui(self) -> None:
        """Создает текстовое поле и прокрутку."""
        ttk.Label(self, text="Справка", style="Heading.TLabel").grid(
            row=0,
            column=0,
            columnspan=2,
            sticky=tk.W,
            pady=(0, 12),
        )
        content = ttk.Frame(self, style="Card.TFrame", padding=1)
        content.grid(row=1, column=0, columnspan=2, sticky=tk.NSEW)
        text = tk.Text(
            content,
            wrap=tk.WORD,
            font=("Segoe UI", 10),
            spacing1=2,
            spacing3=5,
            padx=18,
            pady=18,
            height=24,
            width=86,
        )
        scrollbar = ttk.Scrollbar(content, orient=tk.VERTICAL, command=text.yview)
        text.configure(yscrollcommand=scrollbar.set)

        text.grid(row=0, column=0, sticky=tk.NSEW)
        scrollbar.grid(row=0, column=1, sticky=tk.NS)

        content.rowconfigure(0, weight=1)
        content.columnconfigure(0, weight=1)
        self.rowconfigure(1, weight=1)
        self.columnconfigure(0, weight=1)

        text.insert(tk.END, HELP_TEXT)
        text.configure(state=tk.DISABLED)


class HelpWindow:
    """Отдельное окно справки для совместимости со старым кодом."""

    def __init__(self, parent: tk.Tk) -> None:
        """Создает окно и помещает в него HelpView."""
        self.window = tk.Toplevel(parent)
        self.window.title("Справка")
        self.window.geometry("720x560")
        self.window.minsize(560, 420)
        HelpView(self.window).pack(fill=tk.BOTH, expand=True)
