"""Справка по использованию приложения."""

import tkinter as tk
from tkinter import ttk


HELP_TEXT = """Pomodoro Timer

Что такое Pomodoro
Pomodoro - это способ работать короткими сфокусированными периодами. Обычно пользователь работает 25 минут, затем делает короткий отдых. После нескольких рабочих периодов можно сделать длинный отдых.

Как пользоваться программой
Выберите настройки, нажмите "Старт" и работайте до конца периода. Когда период закончится, программа перейдет к следующему режиму автоматически или остановится, если автопереход выключен.

Кнопка "Старт"
Запускает отсчет текущего периода.

Кнопка "Пауза / Продолжить"
Останавливает отсчет без сброса времени. Повторное нажатие продолжает таймер с того же места.

Кнопка "Пропустить период"
Сразу переводит таймер к следующему периоду. Такой период считается пропущенным и не засчитывается как завершенный.

Кнопка "Сброс"
Возвращает таймер к началу рабочего периода. В статистике это считается сбросом.

Режимы
Работа - время для сфокусированной работы.
Короткий отдых - короткая пауза после рабочего периода.
Длинный отдых - более длинная пауза после заданного количества рабочих периодов.

Настройки
В настройках можно изменить длительности, отключить длинный отдых, выбрать формат времени HH:MM:SS или MM:SS, настроить уведомления, виджет, профили, трей и автозапуск.

Уведомления
Если включен автоматический переход, уведомление будет информационным с кнопкой "Закрыть".
Если включен ручной переход, уведомление покажет кнопку "Продолжить", которая запускает следующий период.

Виджет
Виджет - маленькое отдельное окно с текущим режимом и временем. Его можно перетаскивать мышью за область окна, режим или время. Последняя позиция сохраняется.

Статистика
Статистика показывает время работы и отдыха, завершенные периоды, пропуски, сбросы и полные Pomodoro-циклы за сегодня и за все время.

О программе
Pomodoro Timer - локальное настольное приложение на Python и Tkinter. Оно хранит настройки, профили и статистику на вашем компьютере."""


class HelpView(ttk.Frame):
    """Вкладка справки с прокручиваемым текстом."""

    def __init__(self, parent: tk.Widget) -> None:
        """Создает читаемую справку внутри вкладки."""
        super().__init__(parent, padding=16)
        self._build_ui()

    def _build_ui(self) -> None:
        """Создает текстовое поле и прокрутку."""
        text = tk.Text(
            self,
            wrap=tk.WORD,
            font=("Segoe UI", 10),
            padx=12,
            pady=12,
            height=24,
            width=86,
        )
        scrollbar = ttk.Scrollbar(self, orient=tk.VERTICAL, command=text.yview)
        text.configure(yscrollcommand=scrollbar.set)

        text.grid(row=0, column=0, sticky=tk.NSEW)
        scrollbar.grid(row=0, column=1, sticky=tk.NS)

        self.rowconfigure(0, weight=1)
        self.columnconfigure(0, weight=1)

        text.insert(tk.END, HELP_TEXT)
        text.configure(state=tk.DISABLED)


class HelpWindow:
    """Отдельное окно справки для совместимости со старым кодом."""

    def __init__(self, parent: tk.Tk) -> None:
        """Создает окно и помещает в него HelpView."""
        self.window = tk.Toplevel(parent)
        self.window.title("Справка")
        self.window.geometry("720x560")
        self.window.minsize(560, 420)
        HelpView(self.window).pack(fill=tk.BOTH, expand=True)
