class HelpView(ttk.Frame):
    """Вкладка справки с прокручиваемым текстом."""

    def __init__(self, parent: tk.Widget) -> None:
        """Создает читаемую справку внутри вкладки."""
        super().__init__(parent, padding=16)
        self._build_ui()

    def _build_ui(self) -> None:
        """Создает текстовое поле и прокрутку."""
        text = tk.Text(
            self,
            wrap=tk.WORD,
            font=("Segoe UI", 10),
            padx=12,
            pady=12,
            height=24,
            width=86,
        )
        scrollbar = ttk.Scrollbar(self, orient=tk.VERTICAL, command=text.yview)
        text.configure(yscrollcommand=scrollbar.set)

        text.grid(row=0, column=0, sticky=tk.NSEW)
        scrollbar.grid(row=0, column=1, sticky=tk.NS)

        self.rowconfigure(0, weight=1)
        self.columnconfigure(0, weight=1)

        text.insert(tk.END, HELP_TEXT)
        text.configure(state=tk.DISABLED)


class HelpWindow:
    """Отдельное окно справки для совместимости со старым кодом."""

    def __init__(self, parent: tk.Tk) -> None:
        """Создает окно и помещает в него HelpView."""
        self.window = tk.Toplevel(parent)
        self.window.title("Справка")
        self.window.geometry("720x560")
        self.window.minsize(560, 420)
        HelpView(self.window).pack(fill=tk.BOTH, expand=True)
